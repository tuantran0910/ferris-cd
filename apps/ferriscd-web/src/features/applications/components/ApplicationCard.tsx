import { Box, FolderGit2, GitBranch, Layers, Server } from "lucide-react";
import { Link } from "react-router-dom";
import type { ApplicationSummary } from "../../../api/types";
import { shortRevision } from "../../../utils/format";
import { Badge } from "../../../ui/Badge";
import { CARD_INTERACTIVE_CLASS, CARD_SURFACE_CLASS } from "../../../ui/Card";
import { HealthStatusBadge, SyncStatusBadge } from "../../../ui/StatusBadges";

/** Stagger cap: the last card in a row starts 120ms after the first, which is
 *  the most a grid can spend on entrance motion before it reads as slow. */
const STAGGER_STEP_MS = 30;
const STAGGER_MAX_MS = 120;

function staggerDelay(index: number): string {
  return `${Math.min(index * STAGGER_STEP_MS, STAGGER_MAX_MS)}ms`;
}

export interface ApplicationCardProps {
  app: ApplicationSummary;
  /** Router state carried from the list so "Back to Applications" restores
   *  the operator's exact filtered view. */
  listState: { listSearch: string };
  /** Position in the grid, used only for the entrance stagger. */
  index?: number;
}

export function ApplicationCard({ app, listState, index = 0 }: ApplicationCardProps) {
  return (
    <Link
      to={`/applications/${encodeURIComponent(app.namespace)}/${encodeURIComponent(app.name)}`}
      state={listState}
      data-testid={`app-card-${app.namespace}-${app.name}`}
      style={{ animationDelay: staggerDelay(index) }}
      className={`group flex flex-col justify-between p-4 motion-slide-up ${CARD_SURFACE_CLASS} ${CARD_INTERACTIVE_CLASS}`}
    >
      <div>
        <div className="flex items-start justify-between gap-2">
          <div className="min-w-0">
            <p
              className="truncate font-mono text-[11px] text-ink-muted"
              title={app.namespace}
            >
              {app.namespace}
            </p>
            <h2
              className="truncate text-base font-semibold text-ink-strong group-hover:text-accent"
              title={app.name}
            >
              {app.name}
            </h2>
          </div>
          <span
            className="max-w-[45%] shrink-0 truncate rounded-md border border-control bg-canvas px-2 py-0.5 font-mono text-[11px] text-ink-body"
            title={app.project}
          >
            {app.project}
          </span>
        </div>

        {/* Trap Guard T16.2: Always render separate Sync & Health badges */}
        <div className="mt-3 flex flex-wrap gap-2">
          <SyncStatusBadge status={app.sync?.status} />
          <HealthStatusBadge status={app.health?.status} />
        </div>

        {/* `T19.3`: a generated Application says which ApplicationSet owns it, so an operator can
            tell a fleet member from a hand-authored Application at a glance. A plain `<span>`
            badge inside the card link: never a nested control, and the text carries the meaning
            (the tone only reinforces it). */}
        {app.applicationset ? (
          <div className="mt-2 flex flex-wrap">
            <Badge
              data-testid="applicationset-badge"
              data-applicationset={app.applicationset}
              tone="violet"
              title={`Generated by ApplicationSet ${app.applicationset}`}
            >
              <Layers aria-hidden="true" className="h-3.5 w-3.5" />
              <span className="opacity-75">AppSet:</span>
              <span className="max-w-[12rem] truncate font-mono">
                {app.applicationset}
              </span>
            </Badge>
          </div>
        ) : null}

        {/* A list, not a `<dl>`: these rows are source/destination facts, and a definition list
            whose items carry no `<dt>`/`<dd>` pair is an accessibility defect (WCAG 1.3.1, axe
            `definition-list`). */}
        <ul
          aria-label="Source and destination"
          className="mt-4 space-y-1.5 text-xs text-ink-body"
        >
          <li className="flex items-center gap-2">
            <FolderGit2 aria-hidden="true" className="h-3.5 w-3.5 shrink-0 text-ink-muted" />
            <span
              className="min-w-0 truncate font-mono text-ink-body"
              title={app.source.repoUrl}
            >
              {app.source.repoUrl}
            </span>
          </li>
          <li className="flex items-center gap-2">
            <GitBranch aria-hidden="true" className="h-3.5 w-3.5 shrink-0 text-ink-muted" />
            <span
              className="min-w-0 truncate font-mono"
              title={`${app.source.targetRevision} @ ${app.sync?.revision ?? "unknown revision"}`}
            >
              {app.source.targetRevision} ({shortRevision(app.sync?.revision)})
            </span>
          </li>
          <li className="flex items-center gap-2">
            <Server aria-hidden="true" className="h-3.5 w-3.5 shrink-0 text-ink-muted" />
            <span className="min-w-0 truncate font-mono">
              {app.destination.cluster} / {app.destination.namespace}
            </span>
          </li>
        </ul>
      </div>

      <div className="mt-4 flex items-center justify-between border-t border-line pt-3 text-[11px] text-ink-body">
        <span className="inline-flex items-center gap-1">
          <Box aria-hidden="true" className="h-3.5 w-3.5 text-ink-muted" />
          {app.resourceCount} resources
        </span>
        <span className="font-mono text-ink-body">{app.source.renderer}</span>
      </div>
    </Link>
  );
}
