import { render, screen, within } from "@testing-library/react";
import { MemoryRouter } from "react-router-dom";
import { describe, expect, it } from "vitest";
import type { ApplicationSummary } from "../api/types";
import { ApplicationCard } from "../features/applications/components/ApplicationCard";
import { sampleApps } from "./fixtures";

/** A generated `Application` is the one the API labelled `ferriscd.io/applicationset`. */
function generated(overrides: Partial<ApplicationSummary> = {}): ApplicationSummary {
  return { ...sampleApps[0]!, applicationset: "payments-fleet", ...overrides };
}

function handAuthored(): ApplicationSummary {
  const { applicationset: _omitted, ...rest } = sampleApps[1]!;
  return rest;
}

function renderCard(app: ApplicationSummary) {
  return render(
    <MemoryRouter initialEntries={["/"]}>
      <ApplicationCard app={app} listState={{ listSearch: "" }} />
    </MemoryRouter>,
  );
}

describe("ApplicationCard ApplicationSet badge (T19.3)", () => {
  it("badges a generated Application with the ApplicationSet that owns it", () => {
    renderCard(generated());

    const card = screen.getByTestId("app-card-ferriscd-system-payments-api");
    const badge = within(card).getByTestId("applicationset-badge");

    expect(badge).toHaveTextContent("AppSet:payments-fleet");
    expect(badge).toHaveAttribute("data-applicationset", "payments-fleet");
    expect(badge).toHaveAttribute(
      "title",
      "Generated by ApplicationSet payments-fleet",
    );
    // The label is text, not colour-only: a greyscale screenshot still says which fleet it is.
    expect(badge).toHaveTextContent("payments-fleet");
  });

  it("does not badge a hand-authored Application", () => {
    renderCard(handAuthored());

    const card = screen.getByTestId("app-card-ferriscd-system-checkout-web");
    expect(within(card).queryByTestId("applicationset-badge")).toBeNull();
    expect(card).not.toHaveTextContent("AppSet:");
  });

  it("never introduces a nested interactive element inside the card link", () => {
    renderCard(generated());

    const card = screen.getByTestId("app-card-ferriscd-system-payments-api");
    // `ApplicationCard` renders one `<a>`; a badge that was a button/link would nest controls and
    // break keyboard navigation (and the accessible name of the card).
    expect(card.tagName).toBe("A");
    expect(within(card).queryAllByRole("link")).toHaveLength(0);
    expect(within(card).queryAllByRole("button")).toHaveLength(0);
    expect(screen.getByTestId("applicationset-badge").tagName).toBe("SPAN");
  });
});
