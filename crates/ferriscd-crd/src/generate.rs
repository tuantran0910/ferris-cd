//! Deterministic `CustomResourceDefinition` manifest generation.
//!
//! The CRD YAML under `deploy/crds/` is a build artifact of this crate: it is generated
//! from the Rust types with `kube::CustomResourceExt` and committed so cluster installs
//! never depend on a running `ferriscd` binary. Generation is byte-deterministic —
//! serialization order comes from the type definitions and no timestamps or unordered
//! maps are involved — so drift is a pure string equality check.
//!
//! This module deliberately performs no I/O: it renders strings, and the CLI (or a test)
//! owns file access.

use std::path::{Path, PathBuf};

use k8s_openapi::apiextensions_apiserver::pkg::apis::apiextensions::v1::{
    CustomResourceDefinition, JSONSchemaProps, ValidationRule,
};
use kube::CustomResourceExt;

use crate::application::Application;
use crate::applicationset::ApplicationSet;
use crate::project::AppProject;

/// Repository-relative directory holding the generated CRD manifests.
pub const CRD_DIRECTORY: &str = "deploy/crds";

/// File name of the generated `Application` CRD.
pub const APPLICATION_CRD_FILE_NAME: &str = "applications.ferriscd.io.yaml";

/// File name of the generated `AppProject` CRD.
pub const APPPROJECT_CRD_FILE_NAME: &str = "appprojects.ferriscd.io.yaml";

/// Comment block written at the top of the generated `Application` manifest.
///
/// The rendered YAML has nowhere else to put it, and the one thing an installer has to know *before*
/// applying this file is the API-server floor: [`OCI_REFERENCE_RULE`] is written with CEL optional
/// chaining, so an API server older than `1.29` rejects the CRD itself (`kubectl apply` fails with a
/// compilation error naming the rule) instead of quietly skipping the check.
pub const APPLICATION_CRD_HEADER: &str = "\
# FerrisCD `Application` CRD (ferriscd.io/v1alpha1).
#
# Requires Kubernetes >= 1.29. `spec.source.oci` carries a CEL validation rule written with the
# optional-field syntax (`self.?tag.hasValue() || self.?digest.hasValue()`), which earlier API
# servers cannot compile: they reject this CRD at apply time instead of skipping the validation.
#
# Generated by `ferriscd crd generate`; edit `crates/ferriscd-crd/src/generate.rs`, not this file.
";

/// File name of the generated `ApplicationSet` CRD.
pub const APPLICATIONSET_CRD_FILE_NAME: &str = "applicationsets.ferriscd.io.yaml";

/// CEL rule (`T18.3`): exactly one of `spec.source.git` / `spec.source.oci`.
///
/// The rule is written in the same shape as [`crate::SpecValidationError::MissingSource`] /
/// [`crate::SpecValidationError::AmbiguousSource`], so the API server's `422` and the offline
/// `ApplicationSpec::validate` verdict can never disagree.
///
/// `has(self.x)` alone is *not* that shape: it is true for an explicitly null property
/// (`spec: {source: {git: null}}`), while `validate()` sees `None` — the server would accept a
/// source-less `Application` that the controller then refuses. `has(self.x) && self.x != null` is
/// exactly "the property is set to a value", which is what `Option` means after deserialization.
pub const SOURCE_EXCLUSIVE_RULE: &str = "(has(self.git) && self.git != null && !(has(self.oci) && self.oci != null)) || (!(has(self.git) && self.git != null) && has(self.oci) && self.oci != null)";

/// Message reported when [`SOURCE_EXCLUSIVE_RULE`] fails.
pub const SOURCE_EXCLUSIVE_MESSAGE: &str =
    "exactly one of spec.source.git or spec.source.oci must be specified";

/// CEL rule (`T18.3`, corrected in `T18.4`): an OCI reference must be immutable (`tag` or `digest`).
///
/// Null-aware for the same reason as [`SOURCE_EXCLUSIVE_RULE`]: `oci: {tag: null}` is "no tag" to
/// `OciSourceSpec::validate`, so it must be "no tag" here too — `self.?tag.hasValue()` is exactly
/// "present **and** not null".
///
/// ## Why not `has(self.tag) && self.tag != null`
///
/// That spelling does not compile: `tag`/`digest` are `nullable: true` *strings*, so CEL types
/// `self.tag` as `string` and `self.tag != null` is a static error
/// (`found no matching overload for '_!=_' applied to '(string, null)'`). The API server rejected
/// the whole CRD with that rule, so **no cluster could install `applications.ferriscd.io`** — the
/// `T18.4` live suite caught it (`kubectl apply -f deploy/crds` failed at admission of the CRD
/// itself). The object-typed arms of [`SOURCE_EXCLUSIVE_RULE`] are unaffected, because a nullable
/// object is compared as `dyn`/map rather than as a scalar.
///
/// CEL optional chaining (`self.?field`, `.hasValue()`) requires Kubernetes `>= 1.29`; this
/// project targets `1.35` (`k8s-openapi` feature `v1_35`, `deploy/kind-config.yaml`).
pub const OCI_REFERENCE_RULE: &str = "self.?tag.hasValue() || self.?digest.hasValue()";

/// Message reported when [`OCI_REFERENCE_RULE`] fails.
pub const OCI_REFERENCE_MESSAGE: &str =
    "at least one of spec.source.oci.tag or spec.source.oci.digest must be specified";

/// One generated manifest, ready to be written to `<dir>/<file_name>`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CrdDocument {
    /// File name (never contains a directory separator).
    pub file_name: &'static str,
    /// Rendered YAML manifest.
    pub manifest: String,
}

impl CrdDocument {
    /// Returns the path of this document inside `dir`.
    #[must_use]
    pub fn path_in(&self, dir: &Path) -> PathBuf {
        dir.join(self.file_name)
    }
}

/// Failure while rendering a CRD manifest.
#[derive(Debug, thiserror::Error)]
pub enum CrdGenerationError {
    /// The CRD could not be converted to JSON (never expected; kept for completeness).
    #[error("failed to encode the {file} CRD as JSON: {source}")]
    Encode {
        /// File being rendered.
        file: &'static str,
        /// Underlying serialization error.
        #[source]
        source: serde_json::Error,
    },

    /// The CRD could not be rendered to YAML.
    #[error("failed to render the {file} CRD as YAML: {source}")]
    Render {
        /// File being rendered.
        file: &'static str,
        /// Underlying serialization error.
        #[source]
        source: serde_saphyr::SerializeError,
    },
}

/// Returns the generated `Application` CRD object.
///
/// The `CustomResource` derive cannot express `x-kubernetes-validations`, so the two `T18.3` CEL
/// rules are injected here — on the **typed** CRD rather than on the rendered YAML, so anything
/// that applies [`application_crd`] (installers, live tests) gets the same rules the committed
/// manifest carries.
#[must_use]
pub fn application_crd() -> CustomResourceDefinition {
    let mut crd = Application::crd();
    inject_source_validation_rules(&mut crd);
    crd
}

/// Injects the `T18.3` CEL rules into the `spec.source` / `spec.source.oci` schemas.
///
/// Idempotent: the rules are *set*, not appended, so regenerating an already-injected CRD cannot
/// duplicate them (the drift check compares rendered bytes, and a duplicated rule would show up as
/// permanent drift).
fn inject_source_validation_rules(crd: &mut CustomResourceDefinition) {
    for version in &mut crd.spec.versions {
        let Some(schema) = version
            .schema
            .as_mut()
            .and_then(|schema| schema.open_api_v3_schema.as_mut())
        else {
            continue;
        };
        let Some(source) = field_mut(schema, "spec").and_then(|spec| field_mut(spec, "source"))
        else {
            continue;
        };
        set_rules(source, SOURCE_EXCLUSIVE_RULE, SOURCE_EXCLUSIVE_MESSAGE);
        if let Some(oci) = field_mut(source, "oci") {
            set_rules(oci, OCI_REFERENCE_RULE, OCI_REFERENCE_MESSAGE);
        }
    }
}

/// Returns the mutable `name` property of `schema`.
fn field_mut<'a>(schema: &'a mut JSONSchemaProps, name: &str) -> Option<&'a mut JSONSchemaProps> {
    schema.properties.as_mut()?.get_mut(name)
}

/// Sets the single CEL rule of `schema` to `rule`.
fn set_rules(schema: &mut JSONSchemaProps, rule: &str, message: &str) {
    schema.x_kubernetes_validations = Some(vec![ValidationRule {
        rule: rule.to_owned(),
        message: Some(message.to_owned()),
        ..ValidationRule::default()
    }]);
}

/// Returns the generated `AppProject` CRD object.
#[must_use]
pub fn appproject_crd() -> CustomResourceDefinition {
    AppProject::crd()
}

/// Returns the generated `ApplicationSet` CRD object.
#[must_use]
pub fn applicationset_crd() -> CustomResourceDefinition {
    ApplicationSet::crd()
}

/// Renders every CRD manifest in a stable order (`Application`, `AppProject`, `ApplicationSet`).
pub fn crd_documents() -> Result<Vec<CrdDocument>, CrdGenerationError> {
    Ok(vec![
        CrdDocument {
            file_name: APPLICATION_CRD_FILE_NAME,
            manifest: render_crd(APPLICATION_CRD_FILE_NAME, &application_crd())?,
        },
        CrdDocument {
            file_name: APPPROJECT_CRD_FILE_NAME,
            manifest: render_crd(APPPROJECT_CRD_FILE_NAME, &appproject_crd())?,
        },
        CrdDocument {
            file_name: APPLICATIONSET_CRD_FILE_NAME,
            manifest: render_crd(APPLICATIONSET_CRD_FILE_NAME, &applicationset_crd())?,
        },
    ])
}

/// Renders a single CRD as YAML.
///
/// The server-populated `status` stanza is dropped so the committed manifest is a pure
/// input object. The `Application` manifest additionally carries
/// [`APPLICATION_CRD_HEADER`] — the Kubernetes floor an installer needs before applying it.
pub fn render_crd(
    file_name: &'static str,
    crd: &CustomResourceDefinition,
) -> Result<String, CrdGenerationError> {
    let mut value = serde_json::to_value(crd).map_err(|source| CrdGenerationError::Encode {
        file: file_name,
        source,
    })?;
    if let Some(object) = value.as_object_mut() {
        object.remove("status");
    }
    let rendered =
        serde_saphyr::to_string(&value).map_err(|source| CrdGenerationError::Render {
            file: file_name,
            source,
        })?;
    Ok(if file_name == APPLICATION_CRD_FILE_NAME {
        format!("{APPLICATION_CRD_HEADER}{rendered}")
    } else {
        rendered
    })
}

